-- 14. Tips
CREATE TABLE IF NOT EXISTS public.tips (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  origin_type text NOT NULL CHECK (origin_type IN ('sale', 'rental')),
  origin_id uuid NOT NULL,
  tip_date text NOT NULL,
  amount_bs numeric NOT NULL DEFAULT 0 CHECK (amount_bs >= 0),
  amount_usd numeric CHECK (amount_usd IS NULL OR amount_usd >= 0),
  exchange_rate_used numeric CHECK (exchange_rate_used IS NULL OR exchange_rate_used > 0),
  capture_payment_method text NOT NULL CHECK (capture_payment_method IN ('efectivo', 'pago_movil', 'punto_venta', 'divisa')),
  paid_payment_method text CHECK (paid_payment_method IS NULL OR paid_payment_method IN ('efectivo', 'pago_movil', 'punto_venta', 'divisa')),
  paid_at timestamptz,
  notes text,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'paid')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_tips_origin UNIQUE (origin_type, origin_id)
);

