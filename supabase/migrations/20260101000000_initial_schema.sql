-- 11. Sale Payment Splits
CREATE TABLE IF NOT EXISTS public.sale_payment_splits (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  sale_id uuid NOT NULL REFERENCES public.sales(id) ON DELETE CASCADE,
  payment_method text NOT NULL CHECK (payment_method IN ('efectivo', 'pago_movil', 'punto_venta', 'divisa')),
  amount_bs numeric(12,2) NOT NULL CHECK (amount_bs >= 0),
  amount_usd numeric(12,2) CHECK (amount_usd IS NULL OR amount_usd >= 0),
  exchange_rate_used numeric(12,4) CHECK (exchange_rate_used IS NULL OR exchange_rate_used > 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

